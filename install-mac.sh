#!/usr/bin/env bash
# Install Scranton as a Mac app.
#
#   ./install-mac.sh              build ~/Applications/Scranton.app
#   ./install-mac.sh --login      ...and start the team automatically when you log in
#   ./install-mac.sh --uninstall  remove the app and the login item (keeps this folder and your chat history)
#
# Run it from Terminal, in the Scranton folder, after the CLIs you want
# (claude, codex, agent) are installed and logged in. It remembers the PATH of
# this Terminal so the app can find them later (apps opened from the Dock
# don't see your shell's PATH).

set -euo pipefail
cd "$(dirname "$0")"
REPO="$(pwd)"
APP="$HOME/Applications/Scranton.app"
PLIST="$HOME/Library/LaunchAgents/com.lujin.scranton.plist"

if [ "$(uname)" != "Darwin" ]; then echo "This installer is for macOS."; exit 1; fi

if [ "${1:-}" = "--uninstall" ]; then
    launchctl unload "$PLIST" 2>/dev/null || true
    rm -f "$PLIST"
    rm -rf "$APP"
    echo "Removed Scranton.app and the login item. Your Scranton folder and data/ are untouched."
    exit 0
fi

# --- prerequisites ---------------------------------------------------------
missing=""
command -v python3 >/dev/null 2>&1 || missing="$missing python"
command -v tmux >/dev/null 2>&1 || missing="$missing tmux"
if [ -n "$missing" ]; then
    if command -v brew >/dev/null 2>&1; then
        echo "Installing:$missing"
        # shellcheck disable=SC2086
        brew install $missing
    else
        echo "Missing:$missing. Install Homebrew from https://brew.sh, then run this again."
        exit 1
    fi
fi
if ! python3 -c 'import sys; sys.exit(0 if sys.version_info >= (3, 11) else 1)'; then
    echo "Python 3.11 or newer is needed (found $(python3 --version)). Run: brew install python"
    exit 1
fi
if [ ! -x .venv/bin/python ]; then
    echo "Setting up Python environment..."
    python3 -m venv .venv
fi
.venv/bin/python -m pip install -q -r requirements.txt
chmod +x scranton.sh

echo
echo "CLIs found:"
for c in claude codex agent; do
    if command -v "$c" >/dev/null 2>&1; then echo "  ✓ $c"; else echo "  – $c (not installed; teammates using it won't start)"; fi
done
[ -n "${ANTHROPIC_API_KEY:-}" ] && echo "  ! ANTHROPIC_API_KEY is set in this Terminal. Remove it, or Claude bills the API instead of your plan."
[ -n "${OPENAI_API_KEY:-}" ] && echo "  ! OPENAI_API_KEY is set in this Terminal. Remove it, or Codex may bill the API instead of your plan."

# --- the .app --------------------------------------------------------------
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# PATH without any API-key variables; only PATH is baked in.
SAFE_PATH="$PATH"

cat > "$APP/Contents/MacOS/Scranton" <<EOF
#!/bin/bash
# Generated by install-mac.sh. Re-run the installer if you move the Scranton folder.
export PATH="$SAFE_PATH"
unset ANTHROPIC_API_KEY ANTHROPIC_AUTH_TOKEN OPENAI_API_KEY CURSOR_API_KEY
cd "$REPO" || { osascript -e 'display alert "Scranton folder not found" message "Run install-mac.sh again from the Scranton folder."'; exit 1; }
./scranton.sh start >> data/logs/app.log 2>&1 || {
    osascript -e 'display alert "Scranton could not start" message "See data/logs/app.log and data/logs/server.log in the Scranton folder."'
    exit 1
}
open "http://localhost:8300"
EOF
chmod +x "$APP/Contents/MacOS/Scranton"
mkdir -p data/logs

"$PWD/.venv/bin/python" - "$APP/Contents/Info.plist" <<'PYEOF'
import plistlib, sys
plistlib.dump({
    "CFBundleName": "Scranton", "CFBundleDisplayName": "Scranton",
    "CFBundleIdentifier": "com.lujin.scranton",
    "CFBundleVersion": "1.0", "CFBundleShortVersionString": "1.0",
    "CFBundlePackageType": "APPL", "CFBundleExecutable": "Scranton",
    "CFBundleIconFile": "Scranton", "LSMinimumSystemVersion": "12.0",
}, open(sys.argv[1], "wb"))
PYEOF

# Icon: build an .icns from the 512px logo with the tools every Mac has.
ICONSET="$(mktemp -d)/Scranton.iconset"
mkdir -p "$ICONSET"
for s in 16 32 128 256 512; do
    sips -z $s $s static/scranton-icon.png --out "$ICONSET/icon_${s}x${s}.png" >/dev/null || true
    d=$((s * 2))
    [ "$d" -le 512 ] && { sips -z $d $d static/scranton-icon.png --out "$ICONSET/icon_${s}x${s}@2x.png" >/dev/null || true; }
done
iconutil -c icns "$ICONSET" -o "$APP/Contents/Resources/Scranton.icns" 2>/dev/null || echo "(icon skipped)"
touch "$APP"

# --- start at login (optional) --------------------------------------------
if [ "${1:-}" = "--login" ]; then
    mkdir -p "$(dirname "$PLIST")"
    "$PWD/.venv/bin/python" - "$PLIST" "$REPO" "$SAFE_PATH" <<'PYEOF'
import plistlib, sys
plist, repo, path = sys.argv[1:4]
plistlib.dump({
    "Label": "com.lujin.scranton",
    "ProgramArguments": [f"{repo}/scranton.sh", "start"],
    "EnvironmentVariables": {"PATH": path},
    "WorkingDirectory": repo,
    "RunAtLoad": True,
    # scranton.sh exits after starting things; don't let launchd clean them up.
    "AbandonProcessGroup": True,
    "StandardOutPath": f"{repo}/data/logs/login.log",
    "StandardErrorPath": f"{repo}/data/logs/login.log",
}, open(plist, "wb"))
PYEOF
    launchctl unload "$PLIST" 2>/dev/null || true
    launchctl load "$PLIST"
    echo "Login item installed: the team starts when you log in."
fi

echo
echo "Done. Scranton.app is in ~/Applications."
echo "Open it from Spotlight (Cmd+Space, type Scranton) and drag it to the Dock."
echo "Tip: in Safari, File > Add to Dock gives Scranton its own window."
open "$HOME/Applications"
